#!/usr/bin/env python3
"""make_demos: demos.xml for the Help browser's Examples tab.

WP6. The demo registry inside demo_shAnalysis.m is the one authority for
which cases exist and what they are called; this file is derived from it,
so a case added there appears in the Examples tab without a second edit.

Usage: python3 tools/dev/make_demos.py [--check]
       --check writes nothing and exits non-zero if demos.xml is stale.

Developed by Matthias Weigelt with the help of Claude (Opus 5), 2026-09-08.
"""
import html as H
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "demo_shAnalysis.m")
OUT = os.path.join(ROOT, "demos.xml")

MK = re.compile(r'^\s*mk\("(D\d+)",\s*"([^"]*)",\s*"([^"]*)"', re.M)


def cases():
    with open(SRC, encoding="utf-8") as fh:
        return MK.findall(fh.read())


def render(rows, version):
    items = []
    for cid, title, fns in rows:
        items.append(
            "    <demoitem>\n"
            "      <label>%s - %s</label>\n"
            "      <type>M-file</type>\n"
            "      <source>demo_shAnalysis</source>\n"
            "      <callback>demo_shAnalysis(\"%s\")</callback>\n"
            "      <dependency>%s</dependency>\n"
            "    </demoitem>"
            % (cid, H.escape(title), cid, H.escape(fns)))
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/dev/make_demos.py from the registry in\n"
        "     demo_shAnalysis.m. Do not edit: add the case there. -->\n"
        "<demos>\n"
        "  <name>shAnalysis</name>\n"
        "  <type>toolbox</type>\n"
        "  <icon>HelpIcon.DEMOS</icon>\n"
        "  <description>Selectable demonstrations of every toolbox\n"
        "  capability (v%s). Each case runs standalone and uses real data\n"
        "  when it is present, synthetic known-truth data otherwise.\n"
        "  </description>\n"
        "  <demosection>\n"
        "    <label>Demonstration cases</label>\n"
        "%s\n"
        "  </demosection>\n"
        "</demos>\n" % (version, "\n".join(items)))


def toolbox_version():
    with open(os.path.join(ROOT, "Contents.m"), encoding="utf-8") as fh:
        m = re.search(r"^%\s*Version\s+(\S+)", fh.read(), re.M)
    if not m:
        raise SystemExit("make_demos: no Version line in Contents.m")
    return m.group(1)


def main(argv):
    rows = cases()
    if not rows:
        print("make_demos: no mk(\"Dnn\", ...) rows in demo_shAnalysis.m")
        return 1
    text = render(rows, toolbox_version())
    old = None
    if os.path.isfile(OUT):
        with open(OUT, encoding="utf-8") as fh:
            old = fh.read()
    if "--check" in argv:
        if old != text:
            print("make_demos: demos.xml is stale - rerun "
                  "tools/dev/make_demos.py")
            return 1
        print("make_demos: demos.xml up to date (%d cases)" % len(rows))
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("make_demos: demos.xml written (%d cases)" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
